    private fun buildWingmanHistory(currentPeerText: String): String {
        if (Looper.myLooper() != Looper.getMainLooper()) return "（暂无历史）"
        val adapter = chatAdapterOrNull() ?: return "（暂无历史）"
        val lines = ArrayList<String>()
        val maxLines = MAX_WINGMAN_HISTORY_LINES
        for (item in adapter.data.asReversed()) {
            val msg = item.wkMsg ?: continue
            if (remoteRevoke(msg) != 0) continue
            if (msg.isDeleted != 0) continue
            val text = getTranslatableMessageText(msg)
            if (TextUtils.isEmpty(text)) continue
            if (text == currentPeerText && lines.isEmpty()) continue
            val who = if (getMsgFromType(msg) == WKChatIteMsgFromType.SEND) "我" else "对方"
            lines.add(0, "$who：${text.replace(WHITESPACE_REGEX, " ").take(160)}")
            if (lines.size >= maxLines) break
        }
        return if (lines.isEmpty()) "（暂无历史）" else lines.joinToString("\n")
    }

    private fun parseWingmanReplies(raw: String): List<ChatWingmanReply> {
        val text = raw.trim()
            .removePrefix("```json")
            .removePrefix("```")
            .removeSuffix("```")
            .trim()
        val jsonText = if (text.startsWith("{")) text else Regex("\\{[\\s\\S]*\\}").find(text)?.value ?: return emptyList()
        return try {
            val arr = JSONObject(jsonText).optJSONArray("quick_replies") ?: JSONArray()
            val out = ArrayList<ChatWingmanReply>()
            for (i in 0 until arr.length().coerceAtMost(5)) {
                val obj = arr.optJSONObject(i)
                if (obj != null) {
                    val reply = obj.optString("text", obj.optString("reply", "")).trim()
                    if (reply.isNotEmpty()) {
                        out.add(
                            ChatWingmanReply(
                                label = obj.optString("label", obj.optString("style", "回复")).take(6),
                                text = reply.take(24),
                                style = obj.optString("style", ""),
                                risk = obj.optString("risk", obj.optString("affinity_risk", ""))
                            )
                        )
                    }
                } else {
                    val reply = arr.optString(i, "").trim()
                    if (reply.isNotEmpty()) out.add(ChatWingmanReply("回复", reply.take(24)))
                }
            }
            out
        } catch (_: Exception) {
            emptyList()
        }
    }

    private fun readWingmanCache(key: String): List<ChatWingmanReply> {
        if (Looper.myLooper() == Looper.getMainLooper()) {
            getWingmanMemoryOnMain(key)?.let { return it }
        }
        val preferences = wingmanPreferences()
        return try {
            val raw = preferences.getString(key, "") ?: ""
            if (raw.isBlank()) return emptyList()
            val obj = JSONObject(raw)
            val time = obj.optLong("time", 0L)
            if (time <= 0L || System.currentTimeMillis() - time > WINGMAN_MEMORY_TTL_MS) {
                preferences.edit().remove(key).apply()
                return emptyList()
            }
            val arr = obj.optJSONArray("items") ?: run {
                preferences.edit().remove(key).apply()
                return emptyList()
            }
            val list = ArrayList<ChatWingmanReply>()
            for (i in 0 until arr.length()) {
                val item = arr.optJSONObject(i) ?: continue
                val reply = item.optString("text", "").trim()
                if (reply.isNotEmpty()) {
                    list.add(
                        ChatWingmanReply(
                            item.optString("label", "回复"),
                            reply,
                            item.optString("style", ""),
                            item.optString("risk", "")
                        )
                    )
                }
            }
            if (list.isEmpty()) {
                preferences.edit().remove(key).apply()
            }
            list
        } catch (_: Exception) {
            try {
                preferences.edit().remove(key).apply()
            } catch (_: Exception) {
            }
            emptyList()
        }
    }

    private fun saveWingmanCache(key: String, replies: List<ChatWingmanReply>) {
        try {
