    open fun setAvatar(uiChatMsgItemEntity: WKUIChatMsgItemEntity, avatarView: AvatarView) {
        cancelPendingAvatarFetch(avatarView)
        val msg = uiChatMsgItemEntity.wkMsg
        val sender = msg.from
        val uid = msg.fromUID
        if (TextUtils.isEmpty(uid)) {
            if (sender != null) avatarView.showAvatar(sender)
            return
        }

        val cachedChannel = WKIM.getInstance().channelManager.getChannel(uid, WKChannelType.PERSONAL)
        val displayChannel = when {
            sender != null && !TextUtils.isEmpty(sender.avatar) -> sender
            cachedChannel != null && !TextUtils.isEmpty(cachedChannel.avatar) -> cachedChannel
            sender != null -> sender
            cachedChannel != null
                    && (!TextUtils.isEmpty(cachedChannel.channelName)
                    || !TextUtils.isEmpty(cachedChannel.avatar)) -> cachedChannel
            else -> null
        }
        if (displayChannel != null) {
            avatarView.showAvatar(displayChannel)
        } else {
            avatarView.showAvatar(uid, WKChannelType.PERSONAL, false)
        }

        // A sender/channel object can contain only a nickname. Continue a throttled refresh until
        // either source has a real avatar URL, otherwise recycled group rows can stay on initials forever.
        val hasRealAvatar = (sender != null && !TextUtils.isEmpty(sender.avatar))
                || (cachedChannel != null && !TextUtils.isEmpty(cachedChannel.avatar))
        if (hasRealAvatar) {
            channelFetchTimes.remove(uid)
            avatarBoundUids.remove(avatarView)
        } else {
            scheduleAvatarFetch(avatarView, uid)
        }
    }

    private fun scheduleAvatarFetch(avatarView: AvatarView, uid: String) {
        avatarBoundUids[avatarView] = uid
        val avatarRef = WeakReference(avatarView)
        val runnable = Runnable {
            val target = avatarRef.get() ?: return@Runnable
            avatarFetchRunnables.remove(target)
            if (!target.isAttachedToWindow || avatarBoundUids[target] != uid) return@Runnable
            if (shouldFetchChannelInfo(uid)) {
                WKIM.getInstance().channelManager.fetchChannelInfo(uid, WKChannelType.PERSONAL)
            }
        }
        avatarFetchRunnables[avatarView] = runnable
        mainHandler.postDelayed(runnable, AVATAR_FETCH_DELAY_MS)
    }

    private fun cancelPendingAvatarFetch(avatarView: AvatarView) {
        avatarFetchRunnables.remove(avatarView)?.let { mainHandler.removeCallbacks(it) }
        avatarBoundUids.remove(avatarView)
    }

    private fun shouldFetchChannelInfo(uid: String): Boolean {
        val now = System.currentTimeMillis()
        val last = channelFetchTimes[uid]
        if (last != null && now - last < CHANNEL_FETCH_RETRY_MS) return false
        channelFetchTimes[uid] = now
        while (channelFetchTimes.size > MAX_CHANNEL_FETCH_RECORDS) {
            val first = channelFetchTimes.keys.firstOrNull() ?: break
            channelFetchTimes.remove(first)
        }
        return true
    }

    open fun setMsgTimeAndStatus(
        uiChatMsgItemEntity: WKUIChatMsgItemEntity,
        parentView: View,
        fromType: WKChatIteMsgFromType,
    ) {
        val mMsg = uiChatMsgItemEntity.wkMsg
        val isPlayAnimation = uiChatMsgItemEntity.isUpdateStatus
        val msgTimeTv = parentView.findViewById<TextView>(R.id.msgTimeTv)
        val editedTv = parentView.findViewById<TextView>(R.id.editedTv)
        val statusIV = parentView.findViewById<RLottieImageView>(R.id.statusIV)
        val pinIV = parentView.findViewById<AppCompatImageView>(R.id.pinIV)
        if (msgTimeTv == null || editedTv == null || statusIV == null || pinIV == null || mMsg == null) return

        statusIV.stopAnimation()
        statusIV.setOnClickListener(null)
        statusIV.isClickable = false
        statusIV.setAutoRepeat(false)

        var msgTime = mMsg.timestamp
        if (mMsg.remoteExtra != null && mMsg.remoteExtra.editedAt != 0L) {
            msgTime = mMsg.remoteExtra.editedAt
            editedTv.visibility = VISIBLE
        } else {
            editedTv.visibility = GONE
        }

        pinIV.visibility = if (uiChatMsgItemEntity.isPinned == 1) VISIBLE else GONE
        val is24Hour = WKTimeUtils.getInstance().is24Hour
        val cachedTime = timeTextCache[mMsg]
        val timeText = if (cachedTime != null
            && cachedTime.timestamp == msgTime
            && cachedTime.is24Hour == is24Hour
        ) {
            cachedTime.text
        } else {
            val timeSpace = WKTimeUtils.getInstance().getTimeSpace(msgTime * 1000)
            val time = WKTimeUtils.getInstance().time2HourStr(msgTime * 1000)
            (if (!is24Hour) "$timeSpace $time" else time).also {
                timeTextCache[mMsg] = TimeTextState(msgTime, is24Hour, it)
            }
        }
        if (!TextUtils.equals(msgTimeTv.text, timeText)) msgTimeTv.text = timeText

        val showStatusOnMedia = mMsg.type == WKContentType.WK_IMAGE
            || mMsg.type == WKContentType.WK_GIF
            || mMsg.type == WKContentType.WK_VIDEO
            || mMsg.type == WKContentType.WK_VECTOR_STICKER
            || mMsg.type == WKContentType.WK_EMOJI_STICKER
            || mMsg.type == WKContentType.WK_LOCATION
        val statusColor = if (showStatusOnMedia) {
            ContextCompat.getColor(context, R.color.white)
        } else {
            ContextCompat.getColor(
                context,
                if (fromType == WKChatIteMsgFromType.SEND) {
                    R.color.chat_msg_time_sent
                } else {
                    R.color.chat_msg_time_received
                }
            )
        }
        msgTimeTv.setTextColor(statusColor)
        editedTv.setTextColor(statusColor)
        pinIV.colorFilter = colorFilterCache.getOrPut(statusColor) {
            PorterDuffColorFilter(statusColor, PorterDuff.Mode.MULTIPLY)
        }

        if (mMsg.remoteExtra != null && mMsg.remoteExtra.needUpload == 1) {
            mMsg.status = WKSendMsgResult.send_loading
        }

        if (fromType != WKChatIteMsgFromType.SEND) {
            statusIV.visibility = GONE
            uiChatMsgItemEntity.isUpdateStatus = false
            return
        }

        statusIV.visibility = VISIBLE
        var autoRepeat = false
        val hasReadReceipt = (mMsg.setting?.receipt ?: 0) == 1
                && mMsg.remoteExtra != null
                && mMsg.remoteExtra.readedCount > 0
        val statusResource: Int
        val statusName: String
        if (hasReadReceipt) {
            statusResource = R.raw.ticks_double
            statusName = "ticks_double"
        } else {
            when (mMsg.status) {
                WKSendMsgResult.send_success -> {
                    statusResource = R.raw.ticks_single
                    statusName = "ticks_single"
                }
                WKSendMsgResult.send_loading -> {
                    autoRepeat = true
                    statusResource = R.raw.msg_sending
                    statusName = "msg_sending"
                }
                else -> {
                    statusIV.isClickable = true
                    statusIV.setOnClickListener { handleResendClick(mMsg) }
                    statusResource = R.raw.error
                    statusName = "error"
                }
            }
        }
        val previousState = statusIV.tag as? StatusDrawableState
        val drawable = if (previousState != null && previousState.resourceId == statusResource) {
            previousState.drawable
        } else {
            if (previousState != null) {
                statusIV.clearAnimationDrawable()
                previousState.drawable.recycle()
            }
            RLottieDrawable(
                context,
                statusResource,
                statusName,
                AndroidUtilities.dp(18f),
                AndroidUtilities.dp(18f)
            ).also {
                statusIV.tag = StatusDrawableState(statusResource, it)
                statusIV.setAnimation(it)
            }
        }

        val tintColor = if (mMsg.status <= WKSendMsgResult.send_success) {
            statusColor
        } else if (showStatusOnMedia) {
            ContextCompat.getColor(context, R.color.white)
        } else {
            ContextCompat.getColor(context, R.color.reminderColor)
        }
        Theme.setColorFilter(statusIV, tintColor)
        statusIV.setAutoRepeat(autoRepeat)
        if (autoRepeat || isPlayAnimation) {
            statusIV.playAnimation()
        } else {
            drawable.currentFrame = drawable.framesCount - 1
        }
        uiChatMsgItemEntity.isUpdateStatus = false
    }

    private fun handleResendClick(mMsg: WKMsg) {
        if (mMsg.status == WKSendMsgResult.send_success) return
        if (!canResendMsg(mMsg.channelID, mMsg.channelType)) {
            WKToastUtils.getInstance().showToastNormal(context.getString(R.string.forbidden_can_not_resend))
            return
        }
        var content = context.getString(R.string.str_resend_msg_tips)
        when (mMsg.status) {
            WKSendMsgResult.send_fail -> content = context.getString(R.string.str_resend_msg_tips)
            WKSendMsgResult.no_relation -> content = context.getString(R.string.no_relation_group)
            WKSendMsgResult.black_list -> content = context.getString(
                if (mMsg.channelType == WKChannelType.GROUP) R.string.blacklist_group else R.string.blacklist_user
            )
            WKSendMsgResult.not_on_white_list -> content = context.getString(R.string.no_relation_user)
        }
        WKDialogUtils.getInstance().showDialog(
            context,
            context.getString(R.string.msg_send_fail),
            content,
            true,
            "",
            context.getString(R.string.msg_send_fail_resend),
            0,
            Theme.colorAccount,
        ) { index: Int ->
            if (index == 1) {
                val mMsg1 = WKMsg()
                mMsg1.channelID = mMsg.channelID
                mMsg1.channelType = mMsg.channelType
                mMsg1.setting = mMsg.setting
                mMsg1.header = mMsg.header
                mMsg1.type = mMsg.type
                mMsg1.content = mMsg.content
                mMsg1.baseContentMsgModel = mMsg.baseContentMsgModel
                mMsg1.fromUID = WKConfig.getInstance().uid
                WKIM.getInstance().msgManager.sendMessage(mMsg1)
                WKIM.getInstance().msgManager.deleteWithClientMsgNO(mMsg.clientMsgNO)
            }
        }
    }

    @SuppressLint("ClickableViewAccessibility")
    protected open fun addLongClick(clickView: View, uiChatMsgItemEntity: WKUIChatMsgItemEntity) {
        if (uiChatMsgItemEntity.isShowPinnedMessage) return
        val mMsgConfig: MsgConfig = getMsgConfig(uiChatMsgItemEntity.wkMsg.type)
        var isShowReaction = false
        val obj = EndpointManager.getInstance().invoke("is_show_reaction", CanReactionMenu(uiChatMsgItemEntity.wkMsg, mMsgConfig))
        isShowReaction = (obj as? Boolean) == true
        if (uiChatMsgItemEntity.wkMsg.flame == 1) isShowReaction = false
        val finalIsShowReaction = isShowReaction
        val location = arrayOf(floatArrayOf(0f, 0f))
        val viewLocationInWindow = IntArray(2)

        clickView.setOnTouchListener { _: View?, event: MotionEvent ->
            if (event.action == MotionEvent.ACTION_DOWN) {
                // Store the exact touch point in window coordinates.
                // showAtLocation(Gravity.TOP or START) also uses window coordinates, so popup placement stays stable
                // across nested layouts, status bar offsets, keyboard offsets, and different message cell structures.
                clickView.getLocationInWindow(viewLocationInWindow)
                location[0] = floatArrayOf(
                    viewLocationInWindow[0] + event.x,
                    viewLocationInWindow[1] + event.y
                )
            }
            false
        }
        clickView.setOnLongClickListener {
            performLongPressHaptic(clickView)
            EndpointManager.getInstance().invoke("stop_reaction_animation", null)
            showChatPopup(
                uiChatMsgItemEntity.wkMsg,
                clickView,
                location[0],
                finalIsShowReaction,
                getPopupList(uiChatMsgItemEntity.wkMsg)
            )
            true
        }
    }

    private fun performLongPressHaptic(view: View) {
        try {
            view.isHapticFeedbackEnabled = true
            view.performHapticFeedback(HapticFeedbackConstants.LONG_PRESS)
        } catch (_: Throwable) {
        }
    }

    private fun canWithdraw(mMsg: WKMsg): Boolean {
        if (mMsg.status != WKSendMsgResult.send_success) return false
        var isManager = false
        if (mMsg.channelType == WKChannelType.GROUP) {
            val member = WKIM.getInstance().channelMembersManager.getMember(
                mMsg.channelID,
                mMsg.channelType,
                WKConfig.getInstance().uid
            )
            if (member != null && member.role != WKChannelMemberRole.normal) {
                isManager = true
            }
        }
        var revokeSecond = WKConfig.getInstance().appConfig.revoke_second
        if (revokeSecond == -1 && (mMsg.fromUID == WKConfig.getInstance().uid || isManager)) {
            return true
        }
        if (revokeSecond == 0) revokeSecond = 120
        return (WKTimeUtils.getInstance().currentSeconds - mMsg.timestamp < revokeSecond
                && mMsg.fromUID == WKConfig.getInstance().uid)
                || isManager
    }

