    @SuppressLint("ClickableViewAccessibility")
    protected open fun addLongClick(clickView: View, uiChatMsgItemEntity: WKUIChatMsgItemEntity) {
        if (uiChatMsgItemEntity.isShowPinnedMessage) return
        val mMsgConfig: MsgConfig = getMsgConfig(uiChatMsgItemEntity.wkMsg.type)
        var isShowReaction = false
        val obj = EndpointManager.getInstance().invoke("is_show_reaction", CanReactionMenu(uiChatMsgItemEntity.wkMsg, mMsgConfig))
        if (obj != null) {
            isShowReaction = obj as Boolean
        }
        if (uiChatMsgItemEntity.wkMsg.flame == 1) isShowReaction = false
        val finalIsShowReaction = isShowReaction
        val location = arrayOf(floatArrayOf(0f, 0f))
        val viewLocationInWindow = IntArray(2)

        clickView.setOnTouchListener { _: View?, event: MotionEvent ->
            if (event.action == MotionEvent.ACTION_DOWN) {
                // Store the exact touch point in window coordinates.
                // showAtLocation(Gravity.TOP or START) also uses window coordinates, so popup placement stays stable
                // across nested layouts, status bar offsets, keyboard offsets, and different message cell structures.
                clickView.getLocationInWindow(viewLocationInWindow)
                location[0] = floatArrayOf(
                    viewLocationInWindow[0] + event.x,
                    viewLocationInWindow[1] + event.y
                )
            }
            false
        }
        clickView.setOnLongClickListener {
            performLongPressHaptic(clickView)
            EndpointManager.getInstance().invoke("stop_reaction_animation", null)
            showChatPopup(
                uiChatMsgItemEntity.wkMsg,
                clickView,
                location[0],
                finalIsShowReaction,
                getPopupList(uiChatMsgItemEntity.wkMsg)
            )
            true
        }
    }

    private fun performLongPressHaptic(view: View) {
        try {
            view.isHapticFeedbackEnabled = true
            view.performHapticFeedback(HapticFeedbackConstants.LONG_PRESS)
        } catch (_: Throwable) {
        }
    }

    private fun canWithdraw(mMsg: WKMsg): Boolean {
        if (mMsg.status != WKSendMsgResult.send_success) return false
        var isManager = false
        if (mMsg.channelType == WKChannelType.GROUP) {
            val member = WKIM.getInstance().channelMembersManager.getMember(
                mMsg.channelID,
                mMsg.channelType,
                WKConfig.getInstance().uid
            )
            if (member != null && member.role != WKChannelMemberRole.normal) {
                isManager = true
            }
        }
        var revokeSecond = WKConfig.getInstance().appConfig.revoke_second
        if (revokeSecond == -1 && (mMsg.fromUID == WKConfig.getInstance().uid || isManager)) {
            return true
        }
        if (revokeSecond == 0) revokeSecond = 120
        return (WKTimeUtils.getInstance().currentSeconds - mMsg.timestamp < revokeSecond
                && mMsg.fromUID == WKConfig.getInstance().uid
                && mMsg.status == WKSendMsgResult.send_success)
                || (isManager && mMsg.status == WKSendMsgResult.send_success)
    }

