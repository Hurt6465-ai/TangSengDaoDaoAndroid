    private fun executeAiRequestWithRedirects(endpoint: String, apiKey: String, payload: String): String {
        var currentUrl = endpoint
        var redirectCount = 0
        while (true) {
            val urlObj = URL(currentUrl)
            val conn = (urlObj.openConnection() as HttpURLConnection)
            try {
                conn.instanceFollowRedirects = false
                conn.requestMethod = "POST"
                conn.connectTimeout = 20000
                conn.readTimeout = 30000
                conn.doOutput = true
                conn.setRequestProperty("Content-Type", "application/json; charset=utf-8")
                conn.setRequestProperty("Authorization", "Bearer $apiKey")
                conn.outputStream.use { it.write(payload.toByteArray(StandardCharsets.UTF_8)) }

                val code = conn.responseCode
                if (code in 200..299) {
                    return conn.inputStream.bufferedReader().use { it.readText() }
                }

                if (isRedirectCode(code) && redirectCount < 3) {
                    val location = conn.getHeaderField("Location")
                    if (TextUtils.isEmpty(location)) {
                        throw RuntimeException("HTTP $code redirect without Location")
                    }
                    val nextUrl = URL(urlObj, location)
                    if (!isSafeAiRedirect(urlObj, nextUrl)) {
                        throw RuntimeException("unsafe redirect blocked")
                    }
                    currentUrl = nextUrl.toString()
                    redirectCount++
                    continue
                }

                val err = conn.errorStream?.bufferedReader()?.use { it.readText() } ?: "HTTP $code"
                throw RuntimeException("HTTP $code: " + err.take(160))
            } finally {
                conn.disconnect()
            }
        }
    }

    private fun isSafeAiRedirect(oldUrl: URL, nextUrl: URL): Boolean {
        return oldUrl.protocol.equals(nextUrl.protocol, true)
                && oldUrl.host.equals(nextUrl.host, true)
                && effectivePort(oldUrl) == effectivePort(nextUrl)
    }

    private fun effectivePort(url: URL): Int {
        if (url.port != -1) return url.port
        return if (url.protocol.equals("https", true)) 443 else 80
    }

    private fun isRedirectCode(code: Int): Boolean {
        return code == HttpURLConnection.HTTP_MOVED_PERM
                || code == HttpURLConnection.HTTP_MOVED_TEMP
                || code == HttpURLConnection.HTTP_SEE_OTHER
                || code == 307
                || code == 308
    }

    private fun cleanTranslationText(raw: String): String {
        var text = raw.trim()
            .removePrefix("```json")
            .removePrefix("```")
            .removeSuffix("```")
            .trim()
        if (text.startsWith("{")) {
            try {
                val obj = JSONObject(text)
                val translation = obj.optString("translation", "")
                if (!TextUtils.isEmpty(translation)) return translation.trim()
            } catch (_: Exception) {
                val match = Regex("\"translation\"\\s*:\\s*\"([\\s\\S]*?)\"").find(text)
                if (match != null) {
                    return match.groupValues[1]
                        .replace("\\n", "\n")
                        .replace("\\\"", "\"")
                        .replace("\\/", "/")
                        .trim()
                }
                return ""
            }
        }
        return text
    }

    private fun readAiSetting(key: String, fallback: String): String {
        val cacheKey = "$key|$fallback"
        val now = System.currentTimeMillis()
        synchronized(aiSettingCache) {
            aiSettingCache[cacheKey]?.takeIf { now - it.loadedAt <= AI_SETTING_CACHE_TTL_MS }?.let {
                return it.value
            }
        }
        val value = WKSharedPreferencesUtil.getInstance().getSP(key)
        val resolved = if (!TextUtils.isEmpty(value)) value else fallback
        synchronized(aiSettingCache) {
            aiSettingCache[cacheKey] = AiSettingCacheEntry(resolved, now)
            while (aiSettingCache.size > MAX_AI_SETTING_CACHE_ITEMS) {
                val first = aiSettingCache.keys.firstOrNull() ?: break
                aiSettingCache.remove(first)
            }
        }
        return resolved
    }

    private fun buildTranslationCacheKey(seed: String): String {
        return "chat_translate_cache_" + sha256(seed)
    }

    private fun buildLegacyTranslationCacheKey(seed: String): String {
        return "chat_translate_cache_" + seed.hashCode()
    }

    private fun readTranslationCacheAny(primaryKey: String, legacyKey: String): TranslationCacheHit? {
        val primary = readTranslationCache(primaryKey)
        if (!TextUtils.isEmpty(primary)) return TranslationCacheHit(primaryKey, primary!!)
        val legacy = readTranslationCache(legacyKey)
        if (!TextUtils.isEmpty(legacy)) return TranslationCacheHit(legacyKey, legacy!!)
        return null
    }

    private fun sha256(input: String): String {
        return try {
            val bytes = MessageDigest.getInstance("SHA-256")
                .digest(input.toByteArray(StandardCharsets.UTF_8))
            val out = CharArray(bytes.size * 2)
            for (i in bytes.indices) {
                val value = bytes[i].toInt() and 0xFF
                out[i * 2] = HEX_CHARS[value ushr 4]
                out[i * 2 + 1] = HEX_CHARS[value and 0x0F]
            }
            String(out)
        } catch (_: Exception) {
            input.hashCode().toString()
        }
    }

    private fun readTranslationExpandedAny(primaryKey: String, legacyKey: String): Boolean {
        return readTranslationCacheEntry(primaryKey)?.expanded
            ?: readTranslationCacheEntry(legacyKey)?.expanded
            ?: false
    }

    private fun readTranslationCache(key: String): String? {
        return readTranslationCacheEntry(key)?.text
    }

    private fun readTranslationCacheEntry(key: String): TranslationCacheEntry? {
        readTranslationMemoryEntry(key)?.let { return it }
        if (Looper.myLooper() == Looper.getMainLooper()) return null
        return readTranslationCacheEntryFromDisk(key)?.also { putTranslationMemoryEntry(key, it) }
    }

    private fun readTranslationCacheEntryFromDisk(key: String): TranslationCacheEntry? {
        val now = System.currentTimeMillis()
        return try {
            val preferences = translationPreferences()
            val raw = preferences.getString(key, "") ?: ""
            if (raw.isBlank()) return null
            val obj = JSONObject(raw)
            val time = obj.optLong("time", 0L)
            if (time <= 0L || now - time > TRANSLATION_CACHE_TTL_MS) {
                CACHE_EXECUTOR.execute { preferences.edit().remove(key).apply() }
                return null
            }
            val text = obj.optString("text", "").takeIf { it.isNotBlank() } ?: return null
            TranslationCacheEntry(text, obj.optBoolean("expanded", false), time)
        } catch (_: Exception) {
            CACHE_EXECUTOR.execute {
                try {
                    translationPreferences().edit().remove(key).apply()
                } catch (_: Exception) {
                }
            }
            null
        }
    }

    private fun rememberTranslationMiss(key: String, now: Long = System.currentTimeMillis()) {
        synchronized(translationMemoryCache) {
            translationMissCache[key] = now
            while (translationMissCache.size > MAX_TRANSLATION_MISS_ITEMS) {
                val first = translationMissCache.keys.firstOrNull() ?: break
                translationMissCache.remove(first)
            }
        }
    }

    private fun putTranslationMemoryEntry(key: String, entry: TranslationCacheEntry) {
        synchronized(translationMemoryCache) {
            translationMissCache.remove(key)
            translationMemoryCache[key] = entry
            while (translationMemoryCache.size > MAX_TRANSLATION_MEMORY_ITEMS) {
                val first = translationMemoryCache.keys.firstOrNull() ?: break
                translationMemoryCache.remove(first)
            }
        }
    }

    private fun saveTranslationCache(key: String, translated: String, expanded: Boolean) {
        try {
            val now = System.currentTimeMillis()
            putTranslationMemoryEntry(key, TranslationCacheEntry(translated, expanded, now))
            val obj = JSONObject()
                .put("time", now)
                .put("text", translated)
                .put("expanded", expanded)
            val raw = obj.toString()
            CACHE_EXECUTOR.execute {
                translationPreferences().edit().putString(key, raw).apply()
            }
        } catch (_: Exception) {
        }
    }

    private fun setTranslationExpanded(key: String, expanded: Boolean) {
        try {
            val current = readTranslationMemoryEntry(key) ?: return
            val updated = current.copy(expanded = expanded)
            putTranslationMemoryEntry(key, updated)
            val obj = JSONObject()
                .put("time", updated.time)
                .put("text", updated.text)
                .put("expanded", expanded)
            val raw = obj.toString()
            CACHE_EXECUTOR.execute {
                translationPreferences().edit().putString(key, raw).apply()
            }
        } catch (_: Exception) {
        }
    }

    private fun notifyTranslationChanged(
        mMsg: WKMsg? = null,
        payload: Any = PAYLOAD_TRANSLATION_CHANGED,
        attempt: Int = 0
    ) {
        mainHandler.post {
            try {
                val adapter = chatAdapterOrNull() ?: return@post
                if (mMsg != null) {
                    val index = adapter.data.indexOfFirst { item -> isSameMessage(item.wkMsg, mMsg) }
                    if (index >= 0) {
                        adapter.notifyItemChanged(index + adapter.headerLayoutCount, payload)
                    }
                    return@post
                }
                if (adapter.data.isNotEmpty()) {
                    adapter.notifyItemRangeChanged(adapter.headerLayoutCount, adapter.data.size, payload)
                }
            } catch (_: IllegalStateException) {
                if (attempt < 2) {
                    mainHandler.postDelayed(
                        { notifyTranslationChanged(mMsg, payload, attempt + 1) },
                        16L
                    )
                }
            } catch (_: Exception) {
            }
        }
    }

    @SuppressLint("ClickableViewAccessibility")
    protected fun showChatPopup(
        mMsg: WKMsg,
        v: View,
        local: FloatArray,
        isShowReaction: Boolean,
        list: List<PopupMenuItem>
    ) {
        val adapter = chatAdapterOrNull() ?: return
        val recyclerViewLayout = adapter.conversationContext.recyclerViewLayout
        val mMsgConfig: MsgConfig = getMsgConfig(mMsg.type)
        if (mMsg.flame == 1 && (!mMsgConfig.isCanWithdraw || !canWithdraw(mMsg))) {
            return
        }

        // Avoid stacked popup windows and leaked scrim containers when the user long-presses repeatedly.
        dismissScrimPopup(true)

        val scrimPopupContainerLayout: ChatScrimPopupContainerLayout = object : ChatScrimPopupContainerLayout(context) {
            override fun dispatchKeyEvent(event: KeyEvent): Boolean {
                if (event.keyCode == KeyEvent.KEYCODE_BACK
                    && event.action == KeyEvent.ACTION_UP
                    && scrimPopupWindow != null
                ) {
                    dismissScrimPopup(true)
                    return true
                }
                return super.dispatchKeyEvent(event)
            }

            override fun dispatchTouchEvent(ev: MotionEvent): Boolean {
                val b = super.dispatchTouchEvent(ev)
                if (ev.action == MotionEvent.ACTION_DOWN && !b && scrimPopupWindow != null) {
                    dismissScrimPopup(true)
                }
                return b
            }
        }

        scrimPopupContainerLayout.setOnTouchListener(object : OnTouchListener {
            private val pos = IntArray(2)
            override fun onTouch(v: View, event: MotionEvent): Boolean {
                if (event.actionMasked == MotionEvent.ACTION_DOWN) {
                    if (scrimPopupWindow != null && scrimPopupWindow!!.isShowing) {
                        val contentView = scrimPopupWindow!!.contentView
                        contentView.getLocationInWindow(pos)
                        rect.set(
                            pos[0].toFloat(),
                            pos[1].toFloat(),
                            (pos[0] + contentView.measuredWidth).toFloat(),
                            (pos[1] + contentView.measuredHeight).toFloat()
                        )
                        if (!rect.contains(event.rawX, event.rawY)) {
                            dismissScrimPopup(true)
                        }
                    }
                } else if (event.actionMasked == MotionEvent.ACTION_OUTSIDE) {
                    dismissScrimPopup(true)
                }
                return false
            }
        })

        val popupLayout = ActionBarPopupWindowLayout(
            context,
            R.mipmap.popup_fixed_alert,
            ActionBarPopupWindowLayout.FLAG_USE_SWIPEBACK
        )

        val receiptObj = EndpointManager.getInstance().invoke("show_receipt", mMsg)
        if ((receiptObj as? Boolean) == true) {
                val str = String.format(context.getString(R.string.msg_read_count), mMsg.remoteExtra?.readedCount ?: 0)
                val subItem1 = ActionBarMenuSubItem(context, false, false, false)
                subItem1.setTextAndIcon(str, R.mipmap.msg_seen)
                subItem1.setTag(R.id.width_tag, 240)
                subItem1.setMultiline()
                subItem1.setRightIcon(R.mipmap.msg_arrowright)
                popupLayout.addView(subItem1)
                subItem1.setOnClickListener {
                    dismissScrimPopup(false)
                    EndpointManager.getInstance().invoke("chat_activity_touch", null)
                    val adapter = chatAdapterOrNull() ?: return@setOnClickListener
                    EndpointManager.getInstance().invoke(
                        "show_msg_read_detail",
                        ReadMsgDetailMenu(mMsg.messageID, adapter.conversationContext)
                    )
                }
                val subItem2 = ActionBarMenuSubItem(context, false, false, false)
                subItem2.setItemHeight(10)
                subItem2.setBackgroundColor(ContextCompat.getColor(context, R.color.homeColor))
                popupLayout.addView(subItem2, LayoutHelper.createLinear(LayoutHelper.MATCH_PARENT, 10))
        }

        var i = 0
        val size = list.size
        while (i < size) {
            val item = list[i]
            val isTranslateItem = isTranslatePopupItem(item)
            val subItem = ActionBarMenuSubItem(context, false, false, i == list.size - 1)
            subItem.setTextAndIcon(item.text, item.iconResourceID)
            if (isTranslateItem) {
                subItem.setTag(R.id.width_tag, 156)
                subItem.setItemHeight(34)
                subItem.alpha = 0.82f
            } else {
                subItem.setTag(R.id.width_tag, 240)
            }
            subItem.setMultiline()
            if (!TextUtils.isEmpty(item.subText)) {
                subItem.setSubtext(item.subText)
            }
            if (!TextUtils.isEmpty(item.tag) && item.tag == "auto_delete") {
                EndpointManager.getInstance().invoke("chat_popup_item", subItem)
            }
            subItem.setOnClickListener {
                dismissScrimPopup(false)
                item.iClick.onClick()
                EndpointManager.getInstance().invoke("chat_activity_touch", null)
            }
            popupLayout.addView(subItem)
            i++
        }

        popupLayout.backgroundColor = ContextCompat.getColor(context, R.color.screen_bg)
        popupLayout.minimumWidth = AndroidUtilities.dp(200f)
        var reactionsLayout: ReactionsContainerLayout? = null
        val pad = 22
        val sPad = 24
        if (isShowReaction) {
            reactionsLayout = ReactionsContainerLayout(context)
            reactionsLayout.setPadding(
                AndroidUtilities.dp(4f) + if (AndroidUtilities.isRTL) 0 else sPad,
                AndroidUtilities.dp(4f),
                AndroidUtilities.dp(4f) + if (AndroidUtilities.isRTL) sPad else 0,
                AndroidUtilities.dp(pad.toFloat())
            )
            reactionsLayout.setDelegate(ReactionsContainerDelegate { _: View?, reaction: String?, _: Boolean, location: IntArray? ->
                dismissScrimPopup(true)
                EndpointManager.getInstance().invoke(
                    "wk_msg_reaction",
                    MsgReactionMenu(mMsg, reaction, chatAdapterOrNull(), location)
                )
            })
        }

        val activeReactionsLayout = reactionsLayout
        if (isShowReaction && activeReactionsLayout != null) {
            val params = LayoutHelper.createLinear(LayoutHelper.WRAP_CONTENT, 52 + pad, Gravity.START, 0, 0, 0, 0)
            scrimPopupContainerLayout.addView(activeReactionsLayout, params)
            scrimPopupContainerLayout.setReactionsLayout(activeReactionsLayout)
            activeReactionsLayout.setTransitionProgress(0f)
        }
        scrimPopupContainerLayout.clipChildren = false
        val fl = FrameLayout(context)
        fl.addView(popupLayout, LayoutHelper.createFrame(LayoutHelper.MATCH_PARENT, LayoutHelper.WRAP_CONTENT.toFloat()))
        scrimPopupContainerLayout.addView(
            fl,
            LayoutHelper.createLinear(LayoutHelper.MATCH_PARENT, LayoutHelper.WRAP_CONTENT, Gravity.START, 16, if (isShowReaction) -18 else 0, 36, 0)
        )
        scrimPopupContainerLayout.applyViewBottom(fl)
        scrimPopupContainerLayout.setPopupWindowLayout(popupLayout)
        if (popupLayout.swipeBack != null && isShowReaction && activeReactionsLayout != null) {
            popupLayout.swipeBack!!.addOnSwipeBackProgressListener { _: PopupSwipeBackLayout?, toProgress: Float, progress: Float ->
                if (toProgress == 0f) {
                    activeReactionsLayout.startEnterAnimation()
                } else if (toProgress == 1f) {
                    activeReactionsLayout.alpha = 1f - progress
                }
            }
        }

        scrimPopupWindow = object : ActionBarPopupWindow(scrimPopupContainerLayout, LayoutHelper.WRAP_CONTENT, LayoutHelper.WRAP_CONTENT) {
            override fun dismiss() {
                super.dismiss()
                if (scrimPopupWindow !== this) return
                scrimPopupWindow = null
            }
        }
        scrimPopupWindow!!.setPauseNotifications(true)
        scrimPopupWindow!!.setDismissAnimationDuration(220)
        scrimPopupWindow!!.isOutsideTouchable = true
        scrimPopupWindow!!.isClippingEnabled = true
        scrimPopupWindow!!.animationStyle = R.style.PopupContextAnimation
        scrimPopupWindow!!.isFocusable = true
        scrimPopupContainerLayout.measure(
            MeasureSpec.makeMeasureSpec(AndroidUtilities.dp(1000f), MeasureSpec.AT_MOST),
            MeasureSpec.makeMeasureSpec(AndroidUtilities.dp(1000f), MeasureSpec.AT_MOST)
        )
        scrimPopupWindow!!.inputMethodMode = ActionBarPopupWindow.INPUT_METHOD_NOT_NEEDED
        scrimPopupWindow!!.softInputMode = WindowManager.LayoutParams.SOFT_INPUT_STATE_UNSPECIFIED
        scrimPopupWindow!!.contentView.isFocusableInTouchMode = true
        popupLayout.setFitItems(false)

        val touchWindowX = local.getOrNull(0) ?: 0f
        val touchWindowY = local.getOrNull(1) ?: 0f
        val recyclerWindowLocation = IntArray(2)
        recyclerViewLayout.getLocationInWindow(recyclerWindowLocation)

        val minPopupX = recyclerWindowLocation[0] + AndroidUtilities.dp(6f)
        val maxPopupX = recyclerWindowLocation[0] + recyclerViewLayout.measuredWidth - AndroidUtilities.dp(6f) - scrimPopupContainerLayout.measuredWidth
        var popupX = (touchWindowX - scrimPopupContainerLayout.measuredWidth - AndroidUtilities.dp(28f)).toInt()
        popupX = popupX.coerceIn(minPopupX, maxPopupX.coerceAtLeast(minPopupX))

        var totalHeight = AndroidUtilities.getScreenHeight()
        val height = scrimPopupContainerLayout.measuredHeight + AndroidUtilities.dp(48f)
        val keyboardHeight = WKConstants.getKeyboardHeight()
        if (keyboardHeight > AndroidUtilities.dp(20f)) {
            totalHeight += keyboardHeight
        }
        val popupY: Int = if (height < totalHeight) {
            var yCandidate = touchWindowY.toInt()
            if (height > AndroidUtilities.dp(240f)) {
                yCandidate += AndroidUtilities.dp(240f) - height / 10 * 7
            }
            val minPopupY = recyclerWindowLocation[1] + AndroidUtilities.dp(24f)
            val maxPopupY = totalHeight - height - AndroidUtilities.dp(8f)
            yCandidate.coerceIn(minPopupY, maxPopupY.coerceAtLeast(minPopupY))
        } else {
            0
        }

        val finalPopupX = popupX
        val finalPopupY = popupY
        val showMenu = Runnable {
            if (scrimPopupWindow == null) return@Runnable
            scrimPopupWindow!!.showAtLocation(recyclerViewLayout, Gravity.START or Gravity.TOP, finalPopupX, finalPopupY)
            if (isShowReaction && activeReactionsLayout != null) {
                activeReactionsLayout.startEnterAnimation()
            }
        }
        showMenu.run()
    }

    protected open fun getViewWidth(
        fromType: WKChatIteMsgFromType,
        msgItemEntity: WKUIChatMsgItemEntity
    ): Int {
        val maxWidth = AndroidUtilities.getScreenWidth()
        val checkBoxMarginDp = 30
        val flameWidthDp = if ((msgItemEntity.wkMsg.flame == 1 && msgItemEntity.wkMsg.flameSecond > 0)
            && msgItemEntity.wkMsg.type != WKContentType.WK_IMAGE
            && msgItemEntity.wkMsg.type != WKContentType.WK_VIDEO
        ) 30 else 0
        val pinnedWidthDp = if (msgItemEntity.isShowPinnedMessage) 35 else 0
        val usedDp = if (fromType == WKChatIteMsgFromType.SEND || msgItemEntity.wkMsg.channelType == WKChannelType.PERSONAL) {
            70 + checkBoxMarginDp + flameWidthDp + pinnedWidthDp
        } else {
            70 + 40 + checkBoxMarginDp + flameWidthDp + pinnedWidthDp
        }
        return maxWidth - AndroidUtilities.dp(usedDp.toFloat())
    }

