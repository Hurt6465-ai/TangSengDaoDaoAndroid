                        .put("text", r.text)
                        .put("style", r.style)
                        .put("risk", r.risk)
                )
            }
            val obj = JSONObject().put("time", System.currentTimeMillis()).put("items", arr)
            wingmanPreferences()
                .edit()
                .putString(key, obj.toString())
                .apply()
        } catch (_: Exception) {
        }
    }

    private fun translateTextWithCache(mMsg: WKMsg, text: String, cacheSeed: String) {
        val cacheKey = buildTranslationCacheKey(cacheSeed)
        val apiKey = readAiSetting("chat_ai_key", "")
        if (TextUtils.isEmpty(apiKey)) {
            WKToastUtils.getInstance().showToastNormal(context.getString(R.string.chat_translate_need_api_key))
            return
        }
        val endpoint = readAiSetting("chat_ai_endpoint", "https://api.deepseek.com/v1/chat/completions")
        val model = readAiSetting("chat_ai_model", "deepseek-chat")
        val targetLang = readAiSetting("chat_ai_source_lang", "中文")
        val legacySeed = listOf(getLegacyTranslateId(mMsg, text), text.hashCode().toString(), targetLang, model).joinToString("|")
        val legacyKey = buildLegacyTranslationCacheKey("bubble_$legacySeed")

        mainHandler.post {
            if (translationInflightKeys.contains(cacheKey)) return@post
            translationInflightKeys.add(cacheKey)
            WKToastUtils.getInstance().showToastNormal(context.getString(R.string.chat_translate_translating))

            AI_EXECUTOR.execute {
                try {
                    val cached = readTranslationCacheAny(cacheKey, legacyKey)
                    if (cached != null && !TextUtils.isEmpty(cached.text)) {
                        setTranslationExpanded(cached.key, true)
                        if (cached.key != cacheKey) {
                            saveTranslationCache(cacheKey, cached.text, true)
                        }
                        requestWingmanRepliesIfEnabled(mMsg, text)
                        mainHandler.post { notifyTranslationChanged(mMsg) }
                        return@execute
                    }

                    val translated = requestAiTranslation(endpoint, apiKey, model, targetLang, text)
                    saveTranslationCache(cacheKey, translated, true)
                    requestWingmanRepliesIfEnabled(mMsg, text)
                    mainHandler.post { notifyTranslationChanged(mMsg) }
                } catch (e: Exception) {
                    mainHandler.post {
                        WKToastUtils.getInstance().showToastNormal(context.getString(R.string.chat_translate_failed_prefix) + (e.message ?: ""))
                    }
                } finally {
                    mainHandler.post { translationInflightKeys.remove(cacheKey) }
                }
            }
        }
    }

