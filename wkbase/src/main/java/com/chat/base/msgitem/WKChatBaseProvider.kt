        val obj = EndpointManager.getInstance().invoke("is_register_msg_privacy_module", null)
        if (obj != null && obj is PrivacyMessageMenu) {
            isRegisterMsgPrivacyModule = true
        }

        val list: MutableList<PopupMenuItem> = ArrayList()
        var isAddDelete = true
        val mMsgConfig = getMsgConfig(mMsg.type)

        if (mMsgConfig.isCanWithdraw && canWithdraw(mMsg) && !isRegisterMsgPrivacyModule) {
            isAddDelete = false
            list.add(
                0,
                PopupMenuItem(context.getString(R.string.base_withdraw), R.mipmap.msg_withdraw,
                    object : PopupMenuItem.IClick {
                        override fun onClick() {
                            var msgId = mMsg.messageID
                            if (TextUtils.isEmpty(msgId) || msgId == "0") {
                                msgId = mMsg.clientMsgNO
                            }
                            if (!TextUtils.isEmpty(msgId)) {
                                EndpointManager.getInstance().invoke(
                                    "chat_withdraw_msg",
                                    WithdrawMsgMenu(msgId, mMsg.channelID, mMsg.clientMsgNO, mMsg.channelType)
                                )
                            }
                        }
                    })
            )
        }

        if (mMsgConfig.isCanForward && mMsg.flame == 0) {
            var index = 0
            if (list.isNotEmpty()) index = 1
            list.add(
                index,
                PopupMenuItem(context.getString(R.string.base_forward), R.mipmap.msg_forward,
                    object : PopupMenuItem.IClick {
                        override fun onClick() {
                            var mMessageContent = mMsg.baseContentMsgModel
                            if (mMsg.remoteExtra != null && mMsg.remoteExtra.contentEditMsgModel != null) {
                                mMessageContent = mMsg.remoteExtra.contentEditMsgModel
                            }
                            val chooseChatMenu = ChooseChatMenu(
                                ChatChooseContacts { channelList: List<WKChannel>? ->
                                    if (!channelList.isNullOrEmpty()) {
                                        for (mChannel in channelList) {
                                            var msgContent = mMsg.baseContentMsgModel
                                            if (mMsg.remoteExtra != null && mMsg.remoteExtra.contentEditMsgModel != null) {
                                                msgContent = mMsg.remoteExtra.contentEditMsgModel
                                            }
                                            // Keep the original behavior. If your msg model supports clone/copy,
                                            // clone before modifying mention fields to avoid mutating the source object.
                                            msgContent.mentionAll = 0
                                            msgContent.mentionInfo = null
                                            val option = WKSendOptions()
                                            option.setting.receipt = mChannel.receipt
                                            WKIM.getInstance().msgManager.sendWithOptions(msgContent, mChannel, option)
                                        }
                                        findActivity(context)?.let { activity ->
                                            val viewGroup = activity.findViewById<View>(android.R.id.content).rootView as? ViewGroup
                                            if (viewGroup != null) {
                                                Snackbar.make(viewGroup, context.getString(R.string.str_forward), 1000)
                                                    .setAction("") { }
                                                    .show()
                                            }
                                        }
                                    }
                                },
                                mMessageContent
                            )
                            EndpointManager.getInstance().invoke(EndpointSID.showChooseChatView, chooseChatMenu)
                        }
                    })
            )
        }

        val menus = EndpointManager.getInstance().invokes<ChatItemPopupMenu>(EndpointCategory.wkChatPopupItem, mMsg)
        if (menus != null && menus.isNotEmpty() && mMsg.flame == 0) {
            for (menu in menus) {
                val popupMenu = if (isCopyPopupMenu(menu)) {
                    // Deliberately replace Copy with Translate, as requested.
                    PopupMenuItem("翻译", R.drawable.ic_chat_translate_compact,
                        object : PopupMenuItem.IClick {
                            override fun onClick() {
                                translateWholeMessage(mMsg)
                            }
                        })
                } else {
                    PopupMenuItem(menu.text, menu.imageResource,
                        object : PopupMenuItem.IClick {
                            override fun onClick() {
                                val adapter = chatAdapterOrNull() ?: return
                                menu.iPopupItemClick.onClick(
                                    mMsg,
                                    adapter.conversationContext
                                )
                            }
                        })
                }
                popupMenu.subText = menu.subText
                popupMenu.tag = if (isCopyPopupMenu(menu)) "chat_translate" else menu.tag
                list.add(popupMenu)
            }
        }

        var addIndex = list.size
        val result = EndpointManager.getInstance().invoke("auto_delete", mMsg)
        if (result != null) {
            addIndex = (list.size - 1).coerceAtLeast(0)
        }

        if (mMsgConfig.isCanMultipleChoice && mMsg.flame == 0) {
            list.add(
                addIndex,
                PopupMenuItem(context.getString(R.string.multiple_choice), R.mipmap.msg_select,
                    object : PopupMenuItem.IClick {
                        override fun onClick() {
                            val adapter = chatAdapterOrNull() ?: return
                            var i = 0
                            val size = adapter.data.size
