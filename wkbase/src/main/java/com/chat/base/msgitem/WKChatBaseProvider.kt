    private fun translateWholeMessage(mMsg: WKMsg) {
        val content = getTranslatableMessageText(mMsg)
        if (TextUtils.isEmpty(content)) {
            WKToastUtils.getInstance().showToastNormal("没有可翻译的文字")
            return
        }
        val targetLang = readAiSetting("chat_ai_source_lang", "中文")
        val model = readAiSetting("chat_ai_model", "deepseek-chat")
        val stableId = getStableTranslateId(mMsg, content)
        val cacheSeed = listOf(
            stableId,
            content.hashCode().toString(),
            targetLang,
            model
        ).joinToString("|")
        translateTextWithCache(mMsg, content, "bubble_$cacheSeed")
    }

    private fun getStableTranslateId(mMsg: WKMsg, content: String): String {
        return when {
            !TextUtils.isEmpty(mMsg.clientMsgNO) -> "client:${mMsg.clientMsgNO}"
            !TextUtils.isEmpty(mMsg.messageID) && mMsg.messageID != "0" -> "server:${mMsg.messageID}"
            else -> "content:${mMsg.timestamp}:${mMsg.fromUID}:${mMsg.type}:${content.hashCode()}"
        }
    }

    private fun getLegacyTranslateId(mMsg: WKMsg, content: String): String {
        return when {
            !TextUtils.isEmpty(mMsg.messageID) && mMsg.messageID != "0" -> mMsg.messageID
            !TextUtils.isEmpty(mMsg.clientMsgNO) -> mMsg.clientMsgNO
            else -> content.hashCode().toString()
        }
    }

    protected fun getTranslatableMessageText(mMsg: WKMsg): String {
        var content = ""
        try {
            if (mMsg.remoteExtra != null && mMsg.remoteExtra.contentEditMsgModel != null) {
                content = mMsg.remoteExtra.contentEditMsgModel.displayContent ?: ""
            }
            if (TextUtils.isEmpty(content) && mMsg.baseContentMsgModel != null) {
                content = mMsg.baseContentMsgModel.displayContent ?: ""
            }
            if (TextUtils.isEmpty(content)) {
                content = getShowContent(mMsg.content) ?: ""
            }
        } catch (_: Exception) {
        }
        return content.trim()
    }

    /**
     * Subclasses that implement an inline bubble translate button should call this during every bind.
     * This prevents duplicate buttons on repeated peer messages and fixes cases where the button only appears after scrolling.
     */
    protected fun shouldShowInlineTranslateButton(uiChatMsgItemEntity: WKUIChatMsgItemEntity): Boolean {
        val current = uiChatMsgItemEntity.wkMsg ?: return false
        if (!isValidPeerTranslatableMsg(current)) return false

        val adapter = chatAdapterOrNull() ?: return false
        val token = buildLatestTranslateButtonToken(adapter)
        val latestMsgKey = latestTranslateButtonCache[token] ?: findLatestPeerTranslatableMsgKey(adapter).also { latest ->
            if (!TextUtils.isEmpty(latest)) {
                latestTranslateButtonCache[token] = latest
                trimLatestTranslateButtonCache()
            }
        }

        return latestMsgKey == stableMsgKey(current)
    }

    private fun isValidPeerTranslatableMsg(msg: WKMsg): Boolean {
        if (getMsgFromType(msg) != WKChatIteMsgFromType.RECEIVED) return false
        if (!isSupportedInlineTranslateType(msg)) return false
        if (msg.flame == 1) return false
        if (msg.remoteExtra != null && msg.remoteExtra.revoke != 0) return false
        if (msg.isDeleted != 0) return false
        if (WKContentType.isSystemMsg(msg.type) || WKContentType.isLocalMsg(msg.type)) return false
        return !TextUtils.isEmpty(getTranslatableMessageText(msg))
    }

    private fun isSupportedInlineTranslateType(msg: WKMsg): Boolean {
        return msg.type == WKContentType.WK_TEXT || msg.type == WKContentType.richText
    }

    private fun stableMsgKey(msg: WKMsg): String {
        return when {
            !TextUtils.isEmpty(msg.clientMsgNO) -> "client:${msg.clientMsgNO}"
            !TextUtils.isEmpty(msg.messageID) && msg.messageID != "0" -> "server:${msg.messageID}"
            else -> "fallback:${msg.timestamp}:${msg.fromUID}:${msg.type}:${getTranslatableMessageText(msg).hashCode()}"
        }
    }

    private fun buildLatestTranslateButtonToken(adapter: ChatAdapter): String {
        val fromIndex = (adapter.data.size - 5).coerceAtLeast(0)
        val tail = StringBuilder()
        for (i in fromIndex until adapter.data.size) {
            val msg = adapter.data[i].wkMsg
            tail.append('|')
                .append(msg.clientMsgNO).append(',')
                .append(msg.messageID).append(',')
                .append(msg.timestamp).append(',')
                .append(msg.type).append(',')
                .append(msg.fromUID).append(',')
                .append(msg.remoteExtra?.revoke ?: 0).append(',')
                .append(msg.isDeleted).append(',')
                .append(getTranslatableMessageText(msg).hashCode())
        }
        return adapter.data.size.toString() + tail.toString()
    }

    private fun findLatestPeerTranslatableMsgKey(adapter: ChatAdapter): String {
        val start = (adapter.data.size - MAX_INLINE_TRANSLATE_SCAN).coerceAtLeast(0)
        for (i in adapter.data.size - 1 downTo start) {
            val msg = adapter.data[i].wkMsg ?: continue
            if (!isValidPeerTranslatableMsg(msg)) continue
            return stableMsgKey(msg)
        }
        return ""
    }

    private fun trimLatestTranslateButtonCache() {
        if (latestTranslateButtonCache.size <= 8) return
        latestTranslateButtonCache.clear()
    }

    protected fun getBubbleTranslation(mMsg: WKMsg): String? {
        val content = getTranslatableMessageText(mMsg)
        if (TextUtils.isEmpty(content)) return null
        val keys = getBubbleTranslationCacheKeys(mMsg, content)
        val hit = readTranslationCacheAny(keys.first, keys.second, allowDisk = Looper.myLooper() != Looper.getMainLooper())
        if (hit != null) return hit.text
        enqueueTranslationDiskLoad(mMsg, keys.first, keys.second)
        return null
    }

    protected fun isBubbleTranslationExpanded(mMsg: WKMsg): Boolean {
        val content = getTranslatableMessageText(mMsg)
        if (TextUtils.isEmpty(content)) return false
        val keys = getBubbleTranslationCacheKeys(mMsg, content)
        val hit = readTranslationCacheAny(keys.first, keys.second, allowDisk = Looper.myLooper() != Looper.getMainLooper())
        if (hit != null) return hit.expanded
        enqueueTranslationDiskLoad(mMsg, keys.first, keys.second)
        return false
    }

    private fun getBubbleTranslationCacheKeys(mMsg: WKMsg, content: String): Pair<String, String> {
        val targetLang = readAiSetting("chat_ai_source_lang", "中文")
        val model = readAiSetting("chat_ai_model", "deepseek-chat")
        val cacheSeed = listOf(getStableTranslateId(mMsg, content), content.hashCode().toString(), targetLang, model).joinToString("|")
        val legacySeed = listOf(getLegacyTranslateId(mMsg, content), content.hashCode().toString(), targetLang, model).joinToString("|")
        return Pair(
            buildTranslationCacheKey("bubble_$cacheSeed"),
            buildLegacyTranslationCacheKey("bubble_$legacySeed")
        )
    }

    private fun enqueueTranslationDiskLoad(mMsg: WKMsg, primaryKey: String, legacyKey: String) {
        if (Looper.myLooper() != Looper.getMainLooper()) return
        val loadKey = "$primaryKey|$legacyKey"
        if (translationDiskLoadingKeys.contains(loadKey)) return
        translationDiskLoadingKeys.add(loadKey)
        thread {
            val hit = readTranslationCacheAny(primaryKey, legacyKey, allowDisk = true)
            mainHandler.post {
                translationDiskLoadingKeys.remove(loadKey)
                if (hit != null && !TextUtils.isEmpty(hit.text)) {
                    notifyTranslationChanged(mMsg)
                }
            }
        }
    }

    /**
     * Concrete text-message providers can call this while binding the translated peer message.
     * Render the returned items as bottom reply bubbles; on click call fillInputWithWingmanReply(reply.text).
     */
    protected fun getWingmanReplies(mMsg: WKMsg): List<ChatWingmanReply> {
        val key = getWingmanCacheKey(mMsg) ?: return emptyList()
        if (Looper.myLooper() == Looper.getMainLooper()) {
            getWingmanMemoryOnMain(key)?.let { return it }
            enqueueWingmanDiskLoad(mMsg, key)
            return emptyList()
        }
        return readWingmanCacheFromDisk(key)
    }

    private fun enqueueWingmanDiskLoad(mMsg: WKMsg, key: String) {
        if (Looper.myLooper() != Looper.getMainLooper()) {
            mainHandler.post { enqueueWingmanDiskLoad(mMsg, key) }
            return
        }
        val loadKey = "disk:$key"
        if (wingmanInflightKeys.contains(loadKey)) return
        wingmanInflightKeys.add(loadKey)
        thread {
            val cached = readWingmanCacheFromDisk(key)
            mainHandler.post {
                wingmanInflightKeys.remove(loadKey)
                if (cached.isNotEmpty()) {
                    putWingmanRepliesOnMain(key, cached)
                    notifyTranslationChanged(mMsg, PAYLOAD_WINGMAN_CHANGED)
                }
            }
        }
    }

    protected fun clearWingmanReplies(mMsg: WKMsg? = null) {
        if (Looper.myLooper() != Looper.getMainLooper()) {
            mainHandler.post { clearWingmanReplies(mMsg) }
            return
        }

        if (mMsg == null) {
            wingmanReplyMemory.clear()
            wingmanInflightKeys.clear()
            notifyTranslationChanged(null, PAYLOAD_WINGMAN_CHANGED)
            return
        }
        val key = getWingmanCacheKey(mMsg) ?: return
        wingmanReplyMemory.remove(key)
        wingmanInflightKeys.remove(key)
        thread {
            try {
                context.getSharedPreferences("chat_wingman_cache", Context.MODE_PRIVATE)
                    .edit()
                    .remove(key)
                    .apply()
            } catch (_: Exception) {
            }
        }
        notifyTranslationChanged(mMsg, PAYLOAD_WINGMAN_CHANGED)
    }

    /**
     * Tries to fill the chat input with a selected wingman reply.
     * Prefer registering an Endpoint named chat_fill_input_text in the input panel.
     * Reflection fallbacks are intentionally best-effort to avoid hard coupling to the input implementation.
     */
    protected fun fillInputWithWingmanReply(text: String) {
        if (TextUtils.isEmpty(text)) return
        try {
            val handled = EndpointManager.getInstance().invoke("chat_fill_input_text", text) as? Boolean
            if (handled == true) return
        } catch (_: Throwable) {
        }
        try {
            val ctx = chatAdapterOrNull()?.conversationContext ?: return
            val methodNames = arrayOf("setInputText", "setEditText", "insertText", "setChatInputText", "fillInputText")
            for (name in methodNames) {
                try {
                    val m = ctx.javaClass.methods.firstOrNull { it.name == name && it.parameterTypes.size == 1 && it.parameterTypes[0] == String::class.java }
                    if (m != null) {
                        m.invoke(ctx, text)
                        return
                    }
                } catch (_: Throwable) {
                }
            }
        } catch (_: Throwable) {
        }
    }

    protected fun requestWingmanRepliesForMessage(mMsg: WKMsg) {
        val text = getTranslatableMessageText(mMsg)
        if (TextUtils.isEmpty(text)) return
        requestWingmanRepliesIfEnabled(mMsg, text)
    }

    private fun isWingmanEnabled(): Boolean {
        val raw = readAiSetting("chat_smart_reply_enabled", readAiSetting("chat_wingman_enabled", "0"))
        return raw != "0" && !raw.equals("false", true) && !raw.equals("off", true)
    }

    private fun requestWingmanRepliesIfEnabled(mMsg: WKMsg, peerText: String) {
        if (!isWingmanEnabled()) return
        if (getMsgFromType(mMsg) != WKChatIteMsgFromType.RECEIVED) return
        val safePeerText = normalizeAiInputText(peerText, MAX_WINGMAN_PEER_TEXT_CHARS)
        if (TextUtils.isEmpty(safePeerText)) return
        val apiKey = readAiSetting("chat_ai_key", "")
        if (TextUtils.isEmpty(apiKey)) return
        val key = getWingmanCacheKey(mMsg) ?: return

        mainHandler.post {
            if (getWingmanMemoryOnMain(key) != null) {
                notifyTranslationChanged(mMsg, PAYLOAD_WINGMAN_CHANGED)
                return@post
            }
            if (wingmanInflightKeys.contains(key)) {
                return@post
            }
            val now = System.currentTimeMillis()
            if (wingmanActiveRequestCount >= MAX_WINGMAN_CONCURRENT_REQUESTS) {
                return@post
            }
            if (now - wingmanLastRequestAt < MIN_WINGMAN_REQUEST_INTERVAL_MS) {
                return@post
            }

            val historySnapshot = buildWingmanHistory(safePeerText)
            wingmanInflightKeys.add(key)
            wingmanActiveRequestCount++
            wingmanLastRequestAt = now

            thread {
                try {
                    val cached = readWingmanCacheFromDisk(key)
                    if (cached.isNotEmpty()) {
                        mainHandler.post {
                            finishWingmanRequestOnMain(key)
                            putWingmanRepliesOnMain(key, cached)
                            notifyTranslationChanged(mMsg, PAYLOAD_WINGMAN_CHANGED)
                        }
                        return@thread
                    }

                    val endpoint = readAiSetting("chat_ai_endpoint", "https://api.deepseek.com/v1/chat/completions")
                    val model = readAiSetting("chat_ai_model", "deepseek-chat")
                    val myLang = readAiSetting("chat_ai_source_lang", "中文")
                    val replies = requestAiWingmanReplies(endpoint, apiKey, model, myLang, safePeerText, historySnapshot)
                    if (replies.isNotEmpty()) {
                        saveWingmanCache(key, replies)
                        mainHandler.post {
                            finishWingmanRequestOnMain(key)
                            putWingmanRepliesOnMain(key, replies)
                            notifyTranslationChanged(mMsg, PAYLOAD_WINGMAN_CHANGED)
                        }
                    } else {
                        finishWingmanRequestOnMain(key)
                    }
                } catch (e: Exception) {
                    finishWingmanRequestOnMain(key)
                    warn("wingman-replies", e)
                }
            }
        }
    }

    private fun finishWingmanRequestOnMain(key: String) {
        if (Looper.myLooper() != Looper.getMainLooper()) {
            mainHandler.post { finishWingmanRequestOnMain(key) }
            return
        }
        wingmanInflightKeys.remove(key)
        wingmanActiveRequestCount = (wingmanActiveRequestCount - 1).coerceAtLeast(0)
    }

    private fun putWingmanRepliesOnMain(key: String, replies: List<ChatWingmanReply>) {
        if (Looper.myLooper() != Looper.getMainLooper()) {
            mainHandler.post { putWingmanRepliesOnMain(key, replies) }
            return
        }
        wingmanReplyMemory[key] = WingmanMemoryEntry(System.currentTimeMillis(), replies)
        trimWingmanReplyMemory()
    }

    private fun getWingmanMemoryOnMain(key: String): List<ChatWingmanReply>? {
        if (Looper.myLooper() != Looper.getMainLooper()) return null
        val entry = wingmanReplyMemory[key] ?: return null
        if (System.currentTimeMillis() - entry.time > WINGMAN_MEMORY_TTL_MS) {
            wingmanReplyMemory.remove(key)
            return null
        }
        return entry.replies
    }

    private fun trimWingmanReplyMemory() {
        while (wingmanReplyMemory.size > MAX_WINGMAN_MEMORY_ITEMS) {
            val firstKey = wingmanReplyMemory.keys.firstOrNull() ?: break
            wingmanReplyMemory.remove(firstKey)
        }
    }

    private fun getWingmanCacheKey(mMsg: WKMsg): String? {
        val content = getTranslatableMessageText(mMsg)
        if (TextUtils.isEmpty(content)) return null
        val myLang = readAiSetting("chat_ai_source_lang", "中文")
        val model = readAiSetting("chat_ai_model", "deepseek-chat")
        val stableId = getStableTranslateId(mMsg, content)
        return "chat_wingman_cache_" + sha256(listOf(stableId, content.hashCode().toString(), myLang, model).joinToString("|"))
    }

    private fun normalizeAiInputText(text: String, maxChars: Int): String {
        if (TextUtils.isEmpty(text)) return ""
        return whitespaceRegex.replace(text.trim(), " ").take(maxChars)
    }

    private fun requestAiWingmanReplies(
        endpoint: String,
        apiKey: String,
        model: String,
        myLang: String,
        peerText: String,
        history: String
    ): List<ChatWingmanReply> {
        val prompt = """
            你是我的聊天僚机。根据最近聊天上下文，为我生成可以直接发送的短回复气泡。

            我的语言：$myLang

            要求：
            1. 回复必须使用“我的语言”。
            2. 每条回复尽量短，适合社交软件气泡点击后直接填入输入框。
            3. 口语自然，不油腻，不质问，不情绪绑架，不大段表白。
            4. 根据对方最后一句的情绪和语气接话。
            5. 输出 3 到 5 条，多样化，覆盖轻松、关心、真诚、推进、化解尴尬。
            6. 每条 text 最好 12 个中文字符以内；非中文也尽量短。

            最近聊天历史：
            $history

            对方最后消息：
            $peerText

            只输出 JSON，不要 Markdown，不要解释：
            {
              "quick_replies": [
                {"label":"轻松","text":"可以直接发送的回复","style":"轻松幽默","risk":"安全"}
              ]
            }
        """.trimIndent()

        val payload = JSONObject()
            .put("model", model)
            .put("temperature", 0.45)
            .put(
                "messages",
                JSONArray()
                    .put(JSONObject().put("role", "system").put("content", "你是聊天僚机，只输出可解析 JSON。"))
                    .put(JSONObject().put("role", "user").put("content", prompt))
            )
            .toString()

        val response = executeAiRequestWithRedirects(endpoint, apiKey, payload)
        val raw = JSONObject(response)
            .optJSONArray("choices")
            ?.optJSONObject(0)
            ?.optJSONObject("message")
            ?.optString("content")
            ?.trim()
            ?: ""
        if (raw.isEmpty()) return emptyList()
        return parseWingmanReplies(raw)
    }

    private fun buildWingmanHistory(currentPeerText: String): String {
        if (Looper.myLooper() != Looper.getMainLooper()) return "（暂无历史）"
        val adapter = chatAdapterOrNull() ?: return "（暂无历史）"
        val lines = ArrayList<String>()
        val normalizedCurrent = normalizeAiInputText(currentPeerText, MAX_WINGMAN_PEER_TEXT_CHARS)
        var scanned = 0
        for (item in adapter.data.asReversed()) {
            if (scanned >= MAX_WINGMAN_HISTORY_SCAN) break
            scanned++
            val msg = item.wkMsg ?: continue
            if (msg.remoteExtra != null && msg.remoteExtra.revoke != 0) continue
            if (msg.isDeleted != 0) continue
            val text = normalizeAiInputText(getTranslatableMessageText(msg), MAX_WINGMAN_HISTORY_LINE_CHARS)
            if (TextUtils.isEmpty(text)) continue
            if (text == normalizedCurrent && lines.isEmpty()) continue
            val who = if (getMsgFromType(msg) == WKChatIteMsgFromType.SEND) "我" else "对方"
            lines.add(0, "$who：$text")
            if (lines.size >= MAX_WINGMAN_HISTORY_LINES) break
        }
        return if (lines.isEmpty()) "（暂无历史）" else lines.joinToString("\n")
    }

    private fun parseWingmanReplies(raw: String): List<ChatWingmanReply> {
        val text = raw.trim()
            .removePrefix("```json")
            .removePrefix("```")
            .removeSuffix("```")
            .trim()
        val jsonText = if (text.startsWith("{")) text else Regex("\\{[\\s\\S]*\\}").find(text)?.value ?: return emptyList()
        return try {
            val arr = JSONObject(jsonText).optJSONArray("quick_replies") ?: JSONArray()
            val out = ArrayList<ChatWingmanReply>()
            for (i in 0 until arr.length().coerceAtMost(5)) {
                val obj = arr.optJSONObject(i)
                if (obj != null) {
                    val reply = obj.optString("text", obj.optString("reply", "")).trim()
                    if (reply.isNotEmpty()) {
                        out.add(
                            ChatWingmanReply(
                                label = obj.optString("label", obj.optString("style", "回复")).take(6),
                                text = reply.take(24),
                                style = obj.optString("style", ""),
                                risk = obj.optString("risk", obj.optString("affinity_risk", ""))
                            )
                        )
                    }
                } else {
                    val reply = arr.optString(i, "").trim()
                    if (reply.isNotEmpty()) out.add(ChatWingmanReply("回复", reply.take(24)))
                }
            }
            out
        } catch (_: Exception) {
            emptyList()
        }
    }

    private fun readWingmanCache(key: String): List<ChatWingmanReply> {
        if (Looper.myLooper() == Looper.getMainLooper()) {
            return getWingmanMemoryOnMain(key) ?: emptyList()
        }
        return readWingmanCacheFromDisk(key)
    }

    private fun readWingmanCacheFromDisk(key: String): List<ChatWingmanReply> {
        return try {
            val raw = context.getSharedPreferences("chat_wingman_cache", Context.MODE_PRIVATE).getString(key, "") ?: ""
            if (raw.isBlank()) return emptyList()
            val obj = JSONObject(raw)
            val time = obj.optLong("time", 0L)
            if (System.currentTimeMillis() - time > WINGMAN_MEMORY_TTL_MS) return emptyList()
            val arr = obj.optJSONArray("items") ?: return emptyList()
            val list = ArrayList<ChatWingmanReply>()
            for (i in 0 until arr.length()) {
                val item = arr.optJSONObject(i) ?: continue
                val reply = item.optString("text", "").trim()
                if (reply.isNotEmpty()) {
                    list.add(
                        ChatWingmanReply(
                            item.optString("label", "回复"),
                            reply,
                            item.optString("style", ""),
                            item.optString("risk", "")
                        )
                    )
                }
            }
            list
        } catch (_: Exception) {
            emptyList()
        }
    }

    private fun saveWingmanCache(key: String, replies: List<ChatWingmanReply>) {
        try {
            val arr = JSONArray()
            replies.forEach { r ->
                arr.put(
                    JSONObject()
                        .put("label", r.label)
                        .put("text", r.text)
                        .put("style", r.style)
                        .put("risk", r.risk)
                )
            }
            val obj = JSONObject().put("time", System.currentTimeMillis()).put("items", arr)
            context.getSharedPreferences("chat_wingman_cache", Context.MODE_PRIVATE)
                .edit()
                .putString(key, obj.toString())
                .apply()
        } catch (_: Exception) {
        }
    }

    private fun translateTextWithCache(mMsg: WKMsg, text: String, cacheSeed: String) {
        val cacheKey = buildTranslationCacheKey(cacheSeed)
        val apiKey = readAiSetting("chat_ai_key", "")
        if (TextUtils.isEmpty(apiKey)) {
            WKToastUtils.getInstance().showToastNormal("请先在 AI 翻译设置里填写 API Key")
            return
        }
        val endpoint = readAiSetting("chat_ai_endpoint", "https://api.deepseek.com/v1/chat/completions")
        val model = readAiSetting("chat_ai_model", "deepseek-chat")
        val targetLang = readAiSetting("chat_ai_source_lang", "中文")
        val legacySeed = listOf(getLegacyTranslateId(mMsg, text), text.hashCode().toString(), targetLang, model).joinToString("|")
        val legacyKey = buildLegacyTranslationCacheKey("bubble_$legacySeed")

        mainHandler.post {
            if (translationInflightKeys.contains(cacheKey)) return@post
            translationInflightKeys.add(cacheKey)
            WKToastUtils.getInstance().showToastNormal("正在翻译…")

            thread {
                try {
                    val cached = readTranslationCacheAny(cacheKey, legacyKey)
                    if (cached != null && !TextUtils.isEmpty(cached.text)) {
                        setTranslationExpanded(cached.key, true)
                        if (cached.key != cacheKey) {
                            saveTranslationCache(cacheKey, cached.text, true)
                        }
                        requestWingmanRepliesIfEnabled(mMsg, text)
                        mainHandler.post { notifyTranslationChanged(mMsg) }
                        return@thread
                    }

                    val translated = requestAiTranslation(endpoint, apiKey, model, targetLang, text)
                    saveTranslationCache(cacheKey, translated, true)
                    requestWingmanRepliesIfEnabled(mMsg, text)
                    mainHandler.post { notifyTranslationChanged(mMsg) }
                } catch (e: Exception) {
                    mainHandler.post {
                        WKToastUtils.getInstance().showToastNormal("翻译失败：" + (e.message ?: ""))
                    }
                } finally {
                    mainHandler.post { translationInflightKeys.remove(cacheKey) }
                }
            }
        }
    }

