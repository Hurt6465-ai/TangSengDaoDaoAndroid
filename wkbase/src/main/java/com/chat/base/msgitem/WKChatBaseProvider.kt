    private fun addFlameViewIfNeeded(
        baseView: LinearLayout,
        msgItemEntity: WKUIChatMsgItemEntity,
        from: WKChatIteMsgFromType
    ) {
        if (!isAddFlameView(msgItemEntity)) return

        val deleteTimer = SecretDeleteTimer(context)
        deleteTimer.setSize(25)
        val flameSecond: Int = if (msgItemEntity.wkMsg.type == WKContentType.WK_VOICE) {
            val voiceContent = msgItemEntity.wkMsg.baseContentMsgModel as? WKVoiceContent
            max(voiceContent?.timeTrad ?: 0, msgItemEntity.wkMsg.flameSecond)
        } else {
            msgItemEntity.wkMsg.flameSecond
        }

        deleteTimer.setDestroyTime(
            msgItemEntity.wkMsg.clientMsgNO,
            flameSecond,
            msgItemEntity.wkMsg.viewedAt,
            false
        )

        if (from == WKChatIteMsgFromType.RECEIVED) {
            baseView.addView(
                deleteTimer,
                LayoutHelper.createLinear(25, 25, Gravity.CENTER or Gravity.BOTTOM, 5, 0, 0, 0)
            )
        } else {
            baseView.addView(
                deleteTimer,
                0,
                LayoutHelper.createLinear(25, 25, Gravity.CENTER or Gravity.BOTTOM, 0, 0, 5, 0)
            )
        }
        deleteTimer.visibility = if (msgItemEntity.wkMsg.viewed == 0) INVISIBLE else VISIBLE
    }

    private fun addPinnedOpenViewIfNeeded(
        baseView: LinearLayout,
        msgItemEntity: WKUIChatMsgItemEntity,
        from: WKChatIteMsgFromType
    ) {
        if (!msgItemEntity.isShowPinnedMessage) return

        val openMessageFrameLayout = FrameLayout(context)
        openMessageFrameLayout.background = ContextCompat.getDrawable(context, R.drawable.shape_corner_rectangle)
        val openMessageImageView = AppCompatImageView(context)
        openMessageImageView.setImageResource(R.mipmap.filled_open_message)
        openMessageFrameLayout.addView(
            openMessageImageView,
            LayoutHelper.createFrame(25, 25, Gravity.CENTER)
        )

        if (from == WKChatIteMsgFromType.RECEIVED) {
            baseView.addView(
                openMessageFrameLayout,
                LayoutHelper.createLinear(30, 30, Gravity.CENTER or Gravity.BOTTOM, 5, 0, 0, 0)
            )
        } else {
            baseView.addView(
                openMessageFrameLayout,
                0,
                LayoutHelper.createLinear(30, 30, Gravity.CENTER or Gravity.BOTTOM, 0, 0, 5, 0)
            )
        }

        openMessageFrameLayout.setOnClickListener {
            EndpointManager.getInstance().invoke("tip_msg_in_chat", msgItemEntity.wkMsg.clientMsgNO)
            chatAdapterOrNull()?.conversationContext?.closeActivity()
        }
    }

    protected open fun getMsgBgType(
        previousMsg: WKMsg?,
        nowMsg: WKMsg,
        nextMsg: WKMsg?
    ): WKMsgBgType {
        var previousBubble = false
        var nextBubble = false
        val previousIsSystem = previousMsg != null && WKContentType.isSystemMsg(previousMsg.type)
        val nextIsSystem = nextMsg != null && WKContentType.isSystemMsg(nextMsg.type)

        if (previousMsg != null
            && previousMsg.remoteExtra.revoke == 0
            && previousMsg.isDeleted == 0
            && !previousIsSystem
            && !TextUtils.isEmpty(previousMsg.fromUID)
            && previousMsg.fromUID == nowMsg.fromUID
        ) {
            previousBubble = true
        }

        if (nextMsg != null
            && nextMsg.remoteExtra.revoke == 0
            && nextMsg.isDeleted == 0
            && !nextIsSystem
            && !TextUtils.isEmpty(nextMsg.fromUID)
            && nextMsg.fromUID == nowMsg.fromUID
        ) {
            nextBubble = true
        }

        return if (previousBubble) {
            if (nextBubble) WKMsgBgType.center else WKMsgBgType.bottom
        } else {
            if (nextBubble) WKMsgBgType.top else WKMsgBgType.single
        }
    }

    protected open fun isShowAvatar(nowMsg: WKMsg?, nextMsg: WKMsg?): Boolean {
        var nowUID = ""
        var nextUID = ""
        if (nowMsg != null
            && !TextUtils.isEmpty(nowMsg.fromUID)
            && nowMsg.remoteExtra.revoke == 0
            && !WKContentType.isSystemMsg(nowMsg.type)
        ) {
            nowUID = nowMsg.fromUID
        }
        if (nextMsg != null
            && !TextUtils.isEmpty(nextMsg.fromUID)
            && nextMsg.type != WKContentType.screenshot
            && nextMsg.remoteExtra.revoke == 0
            && !WKContentType.isSystemMsg(nextMsg.type)
        ) {
            nextUID = nextMsg.fromUID
        }
        return nowUID != nextUID
    }

    private fun setChoose(
        baseViewHolder: BaseViewHolder,
        uiChatMsgItemEntity: WKUIChatMsgItemEntity
    ) {
        val adapter = chatAdapterOrNull() ?: return
        if (uiChatMsgItemEntity.wkMsg.flame == 1) {
            uiChatMsgItemEntity.isChoose = false
        }
        if (!uiChatMsgItemEntity.isChoose) return

        var count = adapter.data.count { it.isChecked }
        if (!uiChatMsgItemEntity.isChecked && count >= 100) {
            WKToastUtils.getInstance().showToastNormal(context.getString(R.string.max_choose_msg_count))
            return
        }
        uiChatMsgItemEntity.isChecked = !uiChatMsgItemEntity.isChecked
        val checkBox = baseViewHolder.getView<CheckBox>(R.id.checkBox)
        checkBox.setChecked(uiChatMsgItemEntity.isChecked, true)
        count += if (uiChatMsgItemEntity.isChecked) 1 else -1
        adapter.showTitleRightText(count.toString())
    }

    protected fun setFromName(
        uiChatMsgItemEntity: WKUIChatMsgItemEntity,
        from: WKChatIteMsgFromType,
        receivedNameTv: TextView
    ) {
        val bgType: WKMsgBgType = getMsgBgType(
            uiChatMsgItemEntity.previousMsg,
            uiChatMsgItemEntity.wkMsg,
            uiChatMsgItemEntity.nextMsg
        )
        if (uiChatMsgItemEntity.wkMsg.channelType != WKChannelType.GROUP) {
            receivedNameTv.visibility = GONE
            return
        }

        var showName: String? = ""
        receivedNameTv.tag = uiChatMsgItemEntity.wkMsg.fromUID
        if (uiChatMsgItemEntity.wkMsg.from != null && !TextUtils.isEmpty(uiChatMsgItemEntity.wkMsg.from.channelRemark)) {
            showName = uiChatMsgItemEntity.wkMsg.from.channelRemark
        }
        if (TextUtils.isEmpty(showName)) {
            if (uiChatMsgItemEntity.wkMsg.memberOfFrom != null) {
                showName = uiChatMsgItemEntity.wkMsg.memberOfFrom.remark
                if (TextUtils.isEmpty(showName)) {
                    showName = uiChatMsgItemEntity.wkMsg.memberOfFrom.memberRemark
                }
            }
            if (TextUtils.isEmpty(showName) && uiChatMsgItemEntity.wkMsg.from != null) {
                showName = uiChatMsgItemEntity.wkMsg.from.channelName
            }
            if (TextUtils.isEmpty(showName) && uiChatMsgItemEntity.wkMsg.memberOfFrom != null) {
                showName = uiChatMsgItemEntity.wkMsg.memberOfFrom.memberName
            }
        }
        if (receivedNameTv.tag is String && receivedNameTv.tag == uiChatMsgItemEntity.wkMsg.fromUID) {
            receivedNameTv.text = showName ?: ""
        }

        if (!TextUtils.isEmpty(uiChatMsgItemEntity.wkMsg.fromUID)) {
            val colors = WKBaseApplication.getInstance().context.resources.getIntArray(R.array.name_colors)
            val index = (uiChatMsgItemEntity.wkMsg.fromUID.hashCode() and Int.MAX_VALUE) % colors.size
            receivedNameTv.setTextColor(colors[index])
        }

        if (from == WKChatIteMsgFromType.RECEIVED) {
            val showNickName = uiChatMsgItemEntity.showNickName
            receivedNameTv.visibility = if (showNickName && (bgType == WKMsgBgType.single || bgType == WKMsgBgType.top)) VISIBLE else GONE
        } else {
            receivedNameTv.visibility = GONE
        }
    }

    private fun setCheckBox(
        uiChatMsgItemEntity: WKUIChatMsgItemEntity,
        from: WKChatIteMsgFromType,
        checkBox: CheckBox,
        viewContentLayout: View
    ) {
        cancelCheckBoxAnimator(checkBox)
        cancelCheckBoxAnimator(viewContentLayout)

        val chooseOffset = AndroidUtilities.dp(40f).toFloat()
        val targetCheckBoxX = if (uiChatMsgItemEntity.isChoose) chooseOffset else 0f
        val targetContentX = if (uiChatMsgItemEntity.isChoose && from == WKChatIteMsgFromType.RECEIVED) chooseOffset else 0f

        // RecyclerView bind must be deterministic. Do not start a new animator from bind, otherwise
        // recycled holders can slide while scrolling. Explicit UI actions can call animateCheckBoxState().
        checkBox.translationX = targetCheckBoxX
        viewContentLayout.translationX = targetContentX

        checkBox.setResId(context, R.mipmap.round_check2)
        checkBox.setDrawBackground(true)
        checkBox.setHasBorder(true)
        checkBox.setBorderColor(ContextCompat.getColor(context, R.color.white))
        checkBox.setSize(24)
        checkBox.setStrokeWidth(AndroidUtilities.dp(2f))
        checkBox.setColor(Theme.colorAccount, ContextCompat.getColor(context, R.color.white))
