    private fun addFlameViewIfNeeded(
        baseView: LinearLayout,
        msgItemEntity: WKUIChatMsgItemEntity,
        from: WKChatIteMsgFromType
    ) {
        if (!isAddFlameView(msgItemEntity)) return

        val deleteTimer = SecretDeleteTimer(context)
        deleteTimer.setSize(25)
        val flameSecond: Int = if (msgItemEntity.wkMsg.type == WKContentType.WK_VOICE) {
            val voiceContent = msgItemEntity.wkMsg.baseContentMsgModel as? WKVoiceContent
            max(voiceContent?.timeTrad ?: 0, msgItemEntity.wkMsg.flameSecond)
        } else {
            msgItemEntity.wkMsg.flameSecond
        }

        deleteTimer.setDestroyTime(
            msgItemEntity.wkMsg.clientMsgNO,
            flameSecond,
            msgItemEntity.wkMsg.viewedAt,
            false
        )

        if (from == WKChatIteMsgFromType.RECEIVED) {
            baseView.addView(
                deleteTimer,
                LayoutHelper.createLinear(25, 25, Gravity.CENTER or Gravity.BOTTOM, 5, 0, 0, 0)
            )
        } else {
            baseView.addView(
                deleteTimer,
                0,
                LayoutHelper.createLinear(25, 25, Gravity.CENTER or Gravity.BOTTOM, 0, 0, 5, 0)
            )
        }
        deleteTimer.visibility = if (msgItemEntity.wkMsg.viewed == 0) INVISIBLE else VISIBLE
    }

    private fun addPinnedOpenViewIfNeeded(
        baseView: LinearLayout,
        msgItemEntity: WKUIChatMsgItemEntity,
        from: WKChatIteMsgFromType
    ) {
        if (!msgItemEntity.isShowPinnedMessage) return

