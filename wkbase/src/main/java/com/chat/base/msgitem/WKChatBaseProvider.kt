/**
 * Optimized base provider for chat message items.
 *
 * Main fixes in this version:
 * 1. Safe null handling for getChatViewItem() and adapter access.
 * 2. RecyclerView reuse safety for statusIV: visibility, click listener and repeat state are reset every bind.
 * 3. Long-press popup records touch coordinates in window space and clamps the popup in the same coordinate system.
 * 4. Checkbox animation cancels previous AnimatorSet before starting a new one.
 * 5. Width and animation offsets use dp semantics consistently.
 * 6. Translation prompt is high-fidelity and natural, with auto language detection.
 * 7. Translation cache key includes msg id, content hash, target language and model, so edited messages do not show stale translations.
 * 8. notifyTranslationChanged() refreshes the specific message when possible instead of always notifyDataSetChanged().
 * 9. Long-press now triggers haptic feedback before the menu opens.
 * 10. Translation can also request wingman reply bubbles for the translated peer message.
 *
 * Note: the inline translation button near a bubble is usually implemented in a concrete item provider/layout,
 * not in this base class. Use shouldShowInlineTranslateButton(entity) from subclasses so only the latest
 * received text message shows the inline translate button.
