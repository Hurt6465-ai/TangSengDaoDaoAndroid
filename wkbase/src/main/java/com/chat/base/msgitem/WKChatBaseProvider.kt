                                adapter.data[i].isChoose = true
                                if (adapter.data[i].wkMsg.clientMsgNO == mMsg.clientMsgNO) {
                                    adapter.data[i].isChecked = true
                                }
                                adapter.notifyItemChanged(i + adapter.headerLayoutCount, adapter.data[i])
                                i++
                            }
                            adapter.showTitleRightText("1")
                            adapter.showMultipleChoice()
                        }
                    })
            )
            addIndex++
        }

        if (mMsgConfig.isCanReply && mMsg.status == WKSendMsgResult.send_success && mMsg.flame == 0) {
            list.add(
                addIndex,
                PopupMenuItem(context.getString(R.string.msg_reply), R.mipmap.msg_reply,
                    object : PopupMenuItem.IClick {
                        override fun onClick() {
                            chatAdapterOrNull()?.replyMsg(mMsg)
                        }
                    })
            )
            addIndex++
        }

        if (isAddDelete && mMsg.flame == 0 && result == null) {
            list.add(
                addIndex,
                PopupMenuItem(context.getString(R.string.base_delete), R.mipmap.msg_delete,
                    object : PopupMenuItem.IClick {
                        override fun onClick() {
                            handleDeleteClick(mMsg, obj)
                        }
                    })
            )
        }
        return list
    }

    private fun handleDeleteClick(mMsg: WKMsg, privacyObj: Any?) {
        var singleDelete = false
        if (mMsg.status != WKSendMsgResult.send_success) {
            singleDelete = true
        } else if (mMsg.channelType == WKChannelType.GROUP) {
            val loginUID = WKConfig.getInstance().uid
            val member = WKIM.getInstance().channelMembersManager.getMember(mMsg.channelID, mMsg.channelType, loginUID)
            if (member == null || (member.role == WKChannelMemberRole.normal && !TextUtils.isEmpty(mMsg.fromUID) && mMsg.fromUID != loginUID)) {
                singleDelete = true
            }
        }

        if (privacyObj != null && privacyObj is PrivacyMessageMenu && !singleDelete) {
            val checkBoxText: String = if (mMsg.channelType == WKChannelType.GROUP) {
                context.getString(R.string.str_delete_message_for_all)
            } else {
                var showName = ""
                val channel = WKIM.getInstance().channelManager.getChannel(mMsg.channelID, mMsg.channelType)
                if (channel != null) {
                    showName = if (TextUtils.isEmpty(channel.channelRemark)) channel.channelName else channel.channelRemark
                }
                String.format(context.getString(R.string.str_delete_message_also_to), showName)
            }
            WKDialogUtils.getInstance().showCheckBoxDialog(
                context,
                context.getString(R.string.str_delete_message),
                context.getString(R.string.str_delete_message_tip),
                checkBoxText,
                true,
                "",
                context.getString(R.string.base_delete),
                0,
                ContextCompat.getColor(context, R.color.red)
            ) { index, isChecked ->
                if (index == 1) {
                    if (isChecked) {
                        privacyObj.iClick.onDelete(mMsg)
                    } else {
                        EndpointManager.getInstance().invoke("str_delete_msg", mMsg)
                        WKIM.getInstance().msgManager.deleteWithClientMsgNO(mMsg.clientMsgNO)
                    }
                }
            }
        } else {
            WKDialogUtils.getInstance().showDialog(
                context,
                context.getString(R.string.str_delete_message),
                context.getString(R.string.str_delete_message_tip),
                true,
                "",
                context.getString(R.string.base_delete),
                0,
                ContextCompat.getColor(context, R.color.red)
            ) { index ->
                if (index == 1) {
                    EndpointManager.getInstance().invoke("str_delete_msg", mMsg)
                    WKIM.getInstance().msgManager.deleteWithClientMsgNO(mMsg.clientMsgNO)
                }
            }
        }
    }

