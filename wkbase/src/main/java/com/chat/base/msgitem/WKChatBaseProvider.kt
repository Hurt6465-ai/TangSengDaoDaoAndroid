    private fun cancelCheckBoxAnimator(view: View) {
        checkBoxAnimators[view]?.cancel()
        checkBoxAnimators.remove(view)
        view.animate().cancel()
        view.clearAnimation()
    }


    protected fun animateCheckBoxState(
        checkBox: CheckBox,
        viewContentLayout: View,
        targetCheckBoxX: Float,
        targetContentX: Float,
        duration: Long = 200L
    ) {
        cancelCheckBoxAnimator(checkBox)
        cancelCheckBoxAnimator(viewContentLayout)
        val cbAnimator = ObjectAnimator.ofFloat(checkBox, TRANSLATION_X, targetCheckBoxX)
        val contentAnimator = ObjectAnimator.ofFloat(viewContentLayout, TRANSLATION_X, targetContentX)
        val animatorSet = AnimatorSet().apply {
            play(contentAnimator).with(cbAnimator)
            this.duration = duration
            interpolator = DecelerateInterpolator()
            addListener(object : AnimatorListenerAdapter() {
                override fun onAnimationEnd(animation: Animator) {
                    checkBoxAnimators.remove(checkBox)
                    checkBoxAnimators.remove(viewContentLayout)
                }

                override fun onAnimationCancel(animation: Animator) {
                    checkBoxAnimators.remove(checkBox)
                    checkBoxAnimators.remove(viewContentLayout)
                }
            })
        }
        checkBoxAnimators[checkBox] = animatorSet
        checkBoxAnimators[viewContentLayout] = animatorSet
        animatorSet.start()
    }

