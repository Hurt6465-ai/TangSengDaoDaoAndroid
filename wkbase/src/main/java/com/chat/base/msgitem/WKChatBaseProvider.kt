    private fun isAddFlameView(msgItemEntity: WKUIChatMsgItemEntity): Boolean {
        val msg = msgItemEntity.wkMsg
        val voiceDuration = (msg.baseContentMsgModel as? WKVoiceContent)?.timeTrad ?: 0
        val hasDestroyTime = msg.flameSecond > 0 || (msg.type == WKContentType.WK_VOICE && voiceDuration > 0)
        return !(msg.flame == 0
                || WKContentType.isSystemMsg(msg.type)
                || WKContentType.isLocalMsg(msg.type)
                || (msg.flame == 1 && !hasDestroyTime)
                || msg.type == WKContentType.WK_IMAGE
                || msg.type == WKContentType.WK_VIDEO)
    }

    private fun canResendMsg(channelID: String, channelType: Byte): Boolean {
        if (channelType == WKChannelType.PERSONAL) return true
        val mChannel = WKIM.getInstance().channelManager.getChannel(channelID, channelType)
        val member = WKIM.getInstance().channelMembersManager.getMember(channelID, channelType, WKConfig.getInstance().uid)
        if (member != null) {
            if (mChannel != null && mChannel.forbidden == 1) {
                if (member.role == WKChannelMemberRole.admin) return true
                if (member.role == WKChannelMemberRole.manager) return member.forbiddenExpirationTime <= 0L
                return false
            }
            if (member.forbiddenExpirationTime > 0L) return false
        }
        return true
    }

    fun setItemPadding(position: Int, viewGroupLayout: ChatItemView) {
        val adapter = chatAdapterOrNull() ?: return
        if (position !in adapter.data.indices) return

        val currentFromUID: String? = adapter.data[position].wkMsg.fromUID
        val nextFromUID: String? = if (position + 1 <= adapter.data.size - 1) adapter.data[position + 1].wkMsg.fromUID else ""
        val previousFromUID: String? = if (position > 0) adapter.data[position - 1].wkMsg.fromUID else ""

        var top: Int
        var bottom: Int
        if (TextUtils.isEmpty(currentFromUID)) {
            top = AndroidUtilities.dp(4f)
            bottom = AndroidUtilities.dp(4f)
        } else {
            top = if (!TextUtils.isEmpty(previousFromUID) && previousFromUID == currentFromUID) AndroidUtilities.dp(1f) else AndroidUtilities.dp(4f)
            bottom = if (!TextUtils.isEmpty(nextFromUID) && nextFromUID == currentFromUID) AndroidUtilities.dp(1f) else AndroidUtilities.dp(4f)
        }
        if (position == adapter.data.size - 1) bottom = AndroidUtilities.dp(10f)
        if (position == 0) top = AndroidUtilities.dp(10f)
        viewGroupLayout.setPadding(0, top, 0, bottom)
    }

